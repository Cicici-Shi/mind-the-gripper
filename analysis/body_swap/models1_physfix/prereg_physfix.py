def load_pf_fields(path, neps=20):
    out = {}
    for f in sorted(glob.glob(os.path.join(path, "t*_e*_i*.npz"))):
        m = re.search(r"t(\d+)_e(\d+)_i(\d+)\.npz$", f)
        t, e = int(m.group(1)), int(m.group(2))
        if e >= neps:
            continue
        z = np.load(f, allow_pickle=True)
        F = set(z.files)
        r = {}
        for k in ("pf_qacc_count", "pf_qacc_first_step", "pf_r85_armature", "pf_blind"):
            r[k] = np.asarray(z[k]).item() if k in F else None
        r["pf_grip_armature"] = np.asarray(z["pf_grip_armature"], float).ravel() if "pf_grip_armature" in F else None
        r["finger"] = None
        if "qpos" in F and "joint_names" in F:
            names = [str(x) for x in z["joint_names"]]
            ad, tot = pm.qpos_layout(names)
            q = np.asarray(z["qpos"], float)
            if "gripper0_finger_joint" in ad and q.ndim == 2 and q.shape[1] == tot:
                r["finger"] = q[:, ad["gripper0_finger_joint"][0]]
        out[(t, e)] = r
    return out


def close(x, want):
    return x is not None and abs(float(x) - want) <= 1e-12 + 1e-9 * abs(want)


