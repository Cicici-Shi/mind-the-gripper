def gpu_mix(m, cells):
    names = set()
    for c in dict.fromkeys(cells):
        names |= set(m.gpu_comp(c))
    return sorted(names) if (len(names) > 1 or "?" in names) else None


def est_table(m, table, Y=None):
    """copy of prereg_models1.run_est (universe 4) with: Y argument (剔除版); refused cells and GPU mixing withheld."""
    Y = m.Y200 if Y is None else Y
    out = {}
    for nm, terms in table.items():
        cells = [c for _, c in terms]
        ref = [c for c in dict.fromkeys(cells) if c in m.refused]
        if ref:
            out[nm] = {"refused": ref}
            continue
        if any(c not in m.data for c in cells):
            out[nm] = None
            continue
        mix = gpu_mix(m, cells)
        if mix:
            out[nm] = {"gpu_mix": mix}
            continue
        r = m.boot200.est(Y, terms)
        if r is None:
            out[nm] = None
            continue
        r["nsl"] = m.nsl(r["cells"], 4)
        r["need"] = NEED
        r["state"] = pm.slice_status(r["nsl"], NEED)
        out[nm] = r
    return out


