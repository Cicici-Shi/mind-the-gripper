# =============================================================================================== decision rules (pure)
def drop_exists(drop):
    return drop["point"] <= LINES["drop_exists_point"] + EPS and drop["ci95"][1] < 0


def o_verdict(rec, drop):
    if not drop_exists(drop):
        return O_LBL["vanish"]
    h = LINES["half"] * abs(drop["point"])
    if rec["ci95"][1] < h:
        return O_LBL["keep"]
    if rec["ci95"][0] > 0 and rec["point"] >= h - EPS:
        return O_LBL["lost"]
    return O_LBL["unsure"]


def o_family(vs):
    vals = list(vs.values())
    if any(v not in O_LBL.values() for v in vals):
        return "未能判定", "未能判定（" + "，".join(f"{k} {v}" for k, v in vs.items()) + "）"
    if len(set(vals)) == 1:
        return f"{vals[0]}（{len(vals)}/{len(vals)} checkpoint）", f"{vals[0]}（{len(vals)}/{len(vals)} checkpoint）"
    return "checkpoint 条件性", TXT["ckpt_cond"] + "：" + "，".join(f"{k} {v}" for k, v in vs.items())


def o_text(v, k=1):
    for key, lbl in O_LBL.items():
        if v == lbl:
            return TXT["O_" + key].format(k=k)
    return ""


def grasp_triggers(main, old):
    """§7.1 hand-off triggers for one kp20 column (pooled or one cell) against old_normal;
    returns {name: True / False / None (cannot check)}."""
    def g(d, k):
        v = (d or {}).get(k)
        return None if v is None else float(v)
    out = {}
    v = g(main, "no_pad_contact_carried_frac")
    out["无指垫接触而物体被携带 > 1%"] = None if v is None else v > LINES["trig_no_pad_carried"]
    a, b = g(main, "penetration_p90"), g(old, "penetration_p90")
    out["穿透 p90 > 旧配置正常集 2 倍"] = None if (a is None or b is None) else a > LINES["trig_pen_ratio"] * b
    a, b = g(main, "carry_frac_median"), g(old, "carry_frac_median")
    out["携带比例中位 < 旧配置正常集 0.8 倍"] = None if (a is None or b is None) else a < LINES["trig_carry_ratio"] * b
    return out


def d_tier(m, f, suite):
    cs = fam_all_cells(f, suite)
    if any(c in m.refused for c in cs):
        return 2
    n = max((len(m.dkeys.get(c, {})) for c in cs), default=0)
    return 0 if n == 0 else 1


def excl_Y(m, f, suite):
    ex = set()
    for c in fam_all_cells(f, suite):
        ex |= set(m.dkeys.get(c, {}))
    Y = {c: np.array([np.nan if k in ex else v for k, v in zip(m.keys200, y)]) for c, y in m.Y200.items()}
    return Y, sorted(ex)


